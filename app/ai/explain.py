"""Объяснение замечания простым языком.

Описания правил в отчёте короткие и написаны языком стандарта: «отступ
первой строки 1,25 см», «заголовок не выделен полужирным». Что с этим
делать и почему это вообще требуется — из них не следует. Этот модуль
разворачивает замечание в три части: что не так, почему так принято и как
починить руками.

В модель уходит само замечание, а не текст документа.
"""
from __future__ import annotations

from typing import Any

from pydantic import BaseModel, Field

from app.ai.providers import get_provider
from app.ai.schema import strict_schema

SYSTEM = """Ты объясняешь замечания нормоконтроля автору студенческой работы.

Пиши по-русски, спокойно и по делу. Без вступлений, без ободрений, без \
восклицательных знаков. Обращайся на «вы».

Требования к оформлению у каждого вуза свои. Требуемое и фактическое \
значения придут в самом замечании — опирайся на них, а не на то, что \
принято «вообще». Не называй стандарт, если из замечания не следует, \
какой именно применяется.

Три части ответа:
- what: что именно не так в работе, одним-двумя предложениями;
- why: почему такое требование существует. Если причина в конкретном \
стандарте, назови его. Если требование чисто формальное, так и скажи, \
не выдумывай обоснований;
- how: как исправить вручную в текстовом редакторе. Конкретные шаги: \
какое меню, какое поле, какое значение. Пиши так, чтобы подошло и для Word, \
и для LibreOffice Writer. Если замечание исправляется кнопкой \
автоисправления в SmartDoc, упомяни и это.

Ничего не выдумывай: если данных в замечании не хватает, скажи об этом \
в соответствующем поле."""


class Explanation(BaseModel):
    what: str = Field(description="Что не так в работе")
    why: str = Field(description="Почему такое требование существует")
    how: str = Field(description="Как исправить вручную в Word")


def explain_issue(issue: dict[str, Any]) -> dict[str, str]:
    """Разворачивает одно замечание в понятное объяснение.

    Args:
        issue: замечание из отчёта (code, message, description, expected, actual).

    Returns:
        Словарь с полями what, why, how.
    """
    lines = [f"Код замечания: {issue.get('code', 'не указан')}"]
    for key, label in (
        ("message", "Суть"),
        ("description", "Описание правила"),
        ("location", "Место в документе"),
        ("expected", "Требуется"),
        ("actual", "Фактически"),
    ):
        value = issue.get(key)
        if value:
            lines.append(f"{label}: {value}")

    raw = get_provider().parse(
        system=SYSTEM,
        prompt="\n".join(lines),
        schema=strict_schema(Explanation),
    )
    return Explanation.model_validate(raw).model_dump()
